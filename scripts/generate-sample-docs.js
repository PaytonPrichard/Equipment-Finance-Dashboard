#!/usr/bin/env node
// ============================================================
// Generate the sample deal document corpus.
//
//   node scripts/generate-sample-docs.js
//
// Renders each scenario's documents into test-deal-sheets/ and writes
// EXPECTED.json, the answer key that scripts/score-extraction.js grades
// extraction against.
//
// The documents are generated rather than checked in as binaries so the
// corpus is diffable: a change to a borrower's numbers shows up in a code
// review instead of as "Bin 2735 -> 2841 bytes".
//
// Uses puppeteer-core against whatever Chromium the machine already has
// (Chrome or Edge). Nothing new to install. Override with:
//   CHROME_PATH=/path/to/chrome node scripts/generate-sample-docs.js
// ============================================================

const fs = require('fs');
const path = require('path');
const os = require('os');

const OUT_ROOT = path.join(__dirname, '..', 'test-deal-sheets');

const SCENARIOS = [
  require('./sample-docs/granite-ridge'),
];

// ---- Locating a Chromium ----

function findBrowser() {
  if (process.env.CHROME_PATH) return process.env.CHROME_PATH;

  const pf = process.env['ProgramFiles'] || 'C:\\Program Files';
  const pf86 = process.env['ProgramFiles(x86)'] || 'C:\\Program Files (x86)';
  const local = process.env['LOCALAPPDATA'] || '';

  const candidates =
    os.platform() === 'win32'
      ? [
          path.join(pf, 'Google\\Chrome\\Application\\chrome.exe'),
          path.join(pf86, 'Google\\Chrome\\Application\\chrome.exe'),
          path.join(local, 'Google\\Chrome\\Application\\chrome.exe'),
          path.join(pf, 'Microsoft\\Edge\\Application\\msedge.exe'),
          path.join(pf86, 'Microsoft\\Edge\\Application\\msedge.exe'),
        ]
      : os.platform() === 'darwin'
        ? [
            '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
            '/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge',
          ]
        : [
            '/usr/bin/google-chrome',
            '/usr/bin/chromium',
            '/usr/bin/chromium-browser',
            '/usr/bin/microsoft-edge',
          ];

  for (const c of candidates) {
    try {
      if (fs.existsSync(c)) return c;
    } catch {
      /* keep looking */
    }
  }
  return null;
}

// ---- Answer key ----

function buildExpected(scenarios) {
  return {
    _comment:
      'Answer key for the sample document corpus. Generated by scripts/generate-sample-docs.js; ' +
      'graded by scripts/score-extraction.js. Every borrower here is fictional.',
    generatedAt: new Date().toISOString().slice(0, 10),
    scenarios: scenarios.map((s) => ({
      scenario: s.scenario,
      assetClass: s.assetClass,
      moduleKey: s.moduleKey,
      description: s.description,
      dir: path.posix.join(s.assetClass, s.scenario),
      documents: s.documents.map((d) => ({ file: d.file, documentType: d.documentType })),
      truth: s.truth,
      expectedConflicts: s.expectedConflicts || [],
      expectedAbsent: s.expectedAbsent || [],
    })),
  };
}

// ---- Main ----

async function main() {
  const browserPath = findBrowser();
  if (!browserPath) {
    console.error(
      'No Chrome or Edge found. Set CHROME_PATH to a Chromium executable and re-run.',
    );
    process.exit(1);
  }
  console.log('Using browser:', browserPath);

  const puppeteer = require('puppeteer-core');
  const browser = await puppeteer.launch({
    executablePath: browserPath,
    headless: 'new',
    args: ['--no-sandbox', '--disable-dev-shm-usage'],
  });

  let pdfCount = 0;
  let textCount = 0;

  try {
    for (const scenario of SCENARIOS) {
      const dir = path.join(OUT_ROOT, scenario.assetClass, scenario.scenario);
      fs.mkdirSync(dir, { recursive: true });

      for (const doc of scenario.documents) {
        const out = path.join(dir, doc.file);

        if (doc.text !== undefined) {
          fs.writeFileSync(out, doc.text, 'utf-8');
          textCount += 1;
          console.log('  text', path.relative(OUT_ROOT, out));
          continue;
        }

        const pageObj = await browser.newPage();
        // setContent with no external resources, so no network wait needed.
        await pageObj.setContent(doc.html, { waitUntil: 'load' });
        await pageObj.pdf({
          path: out,
          format: 'Letter',
          printBackground: true,
          margin: { top: '0.6in', bottom: '0.6in', left: '0.6in', right: '0.6in' },
        });
        await pageObj.close();
        pdfCount += 1;
        console.log('  pdf ', path.relative(OUT_ROOT, out));
      }
    }

    const expectedPath = path.join(OUT_ROOT, 'EXPECTED.json');
    fs.writeFileSync(expectedPath, JSON.stringify(buildExpected(SCENARIOS), null, 2) + '\n', 'utf-8');
    console.log('  key ', path.relative(OUT_ROOT, expectedPath));
  } finally {
    await browser.close();
  }

  console.log(`\nDone. ${pdfCount} PDF(s), ${textCount} text file(s), ${SCENARIOS.length} scenario(s).`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
